import { test, expect } from '@playwright/test';
import type { BrowserContext, Page } from '@playwright/test';
import path from 'node:path';
test.describe.serial('new Tidewater real-backend workflow', () => {
  let context: BrowserContext; let page: Page;
  const title = `Synthetic browser observation ${Date.now()}`;
  test.beforeAll(async ({ browser, baseURL }) => {
    context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
    page = await context.newPage();
  });
  test.afterAll(async () => { await context?.close(); });
  test('fresh landing and guest workspace load', async () => {
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Good neighbors. Healthier shores.' })).toBeVisible();
    await expect(page.getByText('Your own private demo workspace.', { exact: false })).toBeVisible();
    await page.getByRole('button', { name: 'Explore the working demo' }).click();
    await expect(page.getByRole('heading', { name: 'Your shoreline, at a glance.' })).toBeVisible();
    await expect(page.getByText('6 synthetic · 0 added by you')).toBeVisible();
    await expect(page.locator('.leaflet-tile-loaded').first()).toBeVisible();
    await expect(page.getByText('Teams are synthetic; other visitors have separate workspaces.', { exact: false })).toBeVisible();
  });
  test('private photo submission, matching assignment, claim, start, and completion persist', async () => {
    await page.getByRole('button', { name: 'New report', exact: true }).click();
    const dialog = page.getByRole('dialog');
    await dialog.getByLabel('What did you notice?').fill(title);
    await dialog.getByLabel('A little more detail').fill('Synthetic browser test: litter on a public shoreline. No real incident is represented.');
    await dialog.getByLabel('Location name').fill('QA north beach public access');
    await dialog.getByLabel('Latitude', { exact: true }).fill('');
    await expect(dialog.getByRole('region', { name: /Choose report location/ })).toBeVisible();
    await dialog.getByLabel('Latitude', { exact: true }).fill('31.427');
    await dialog.getByLabel('Longitude', { exact: true }).fill('-81.268');
    await dialog.getByLabel('Report photo').setInputFiles(path.resolve('tests/fixtures/coast-test.jpg'));
    await dialog.getByRole('button', { name: 'Submit report', exact: true }).click();
    await expect(dialog.getByRole('heading', { name: title })).toBeVisible();
    await expect(dialog.getByRole('img', { name: 'Photo attached to this hazard report' })).toBeVisible();
    await dialog.getByLabel('Assign volunteer team').selectOption({ label: 'Shoreline Stewards' });
    await expect(dialog.getByLabel('Assign volunteer team')).toBeEnabled();
    await dialog.getByRole('button', { name: 'Claim this task' }).click();
    await expect(dialog.getByRole('button', { name: 'Start task', exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Start task', exact: true }).click();
    await expect(dialog.getByRole('button', { name: 'Mark complete' })).toBeDisabled();
    await dialog.getByLabel('Completion note', { exact: true }).fill('Synthetic test completion only. No real cleanup was performed.');
    await dialog.getByRole('button', { name: 'Mark complete' }).click();
    await expect(dialog.getByText('Completed', { exact: true })).toBeVisible();
    await expect(dialog.getByLabel('Assign volunteer team')).toBeDisabled();
    await dialog.getByRole('button', { name: 'Close dialog' }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Explore the working demo' }).click();
    await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button', { name: /Reports/ }).click();
    await page.getByLabel('Search reports').fill(title);
    await page.getByRole('button', { name: new RegExp(title) }).click();
    await expect(dialog.getByText('Completed', { exact: true })).toBeVisible();
    await expect(dialog.getByText('Synthetic test completion only. No real cleanup was performed.')).toBeVisible();
    await dialog.getByRole('button', { name: 'Close dialog' }).click();
  });
  test('combined search, category, and status filters, map pins, and team details', async () => {
    const nav = page.getByRole('navigation', { name: 'Workspace navigation' });
    await nav.getByRole('button', { name: /Reports/ }).click();
    await page.getByLabel('Filter by category').selectOption('Flooding');
    await expect(page.locator('.report-row')).toHaveCount(1);
    await page.getByLabel('Search reports').fill('no-such-shoreline');
    await expect(page.getByRole('heading', { name: 'No matching observations.' })).toBeVisible();
    await page.getByRole('button', { name: 'Clear filters' }).click();
    await expect(page.locator('.report-row')).toHaveCount(7);
    await nav.getByRole('button', { name: 'Coast map', exact: true }).click();
    await page.getByRole('button', { name: 'Fishing line along the shoreline', exact: true }).click();
    await expect(page.getByRole('dialog').getByText('Synthetic sample', { exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await nav.getByRole('button', { name: 'Volunteer teams', exact: true }).click();
    await page.getByRole('button', { name: /sample team Shoreline Stewards/i }).click();
    await expect(page.getByRole('dialog').getByText('Collection bags', { exact: true })).toBeVisible();
    await page.keyboard.press('Escape');
  });
  test('activity contains committed report and task updates', async () => {
    await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button', { name: 'Activity', exact: true }).click();
    await expect(page.getByText(`New report: ${title}`, { exact: true })).toBeVisible();
    await expect(page.getByText('Task marked complete by you', { exact: true })).toBeVisible();
    await expect(page.getByText('Task started', { exact: true })).toBeVisible();
    await expect(page.getByText('Team assigned', { exact: true })).toBeVisible();
  });
  test('mobile navigation and keyboard modal remain usable without horizontal overflow', async () => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.getByRole('button', { name: 'Toggle navigation' }).click();
    await page.getByRole('navigation', { name: 'Workspace navigation' }).getByRole('button', { name: 'Overview', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Your shoreline, at a glance.' })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.getByRole('button', { name: 'New report', exact: true }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    expect(await page.evaluate(() => { const d = document.querySelector('dialog')!; return d.contains(document.activeElement); })).toBe(true);
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await page.screenshot({ path: '.local/mobile-workspace.png', fullPage: true });
  });
});
test('authentication failure stays closed instead of showing fake saved records', async ({ page }) => {
  await page.route('**/auth/v1/**', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'Test authentication unavailable' }) }));
  await page.goto('/');
  await page.getByRole('button', { name: 'Explore the working demo' }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Your shoreline, at a glance.' })).toHaveCount(0);
});
